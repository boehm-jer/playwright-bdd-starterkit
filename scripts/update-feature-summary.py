#!/usr/bin/env python3
"""Regenerate FEATURE_SUMMARY.md from the .feature files in ./features.

Lists every scenario name (Scenario and Scenario Outline), grouped under its
feature's title. Features are ordered by file name; scenarios keep file order.

Usage (from anywhere):
    python3 scripts/update-feature-summary.py
"""

import re
from pathlib import Path

BDD_DIR = Path(__file__).resolve().parent.parent
FEATURES_DIR = BDD_DIR / "features"
OUTPUT = BDD_DIR / "FEATURE_SUMMARY.md"

FEATURE_RE = re.compile(r"^\s*Feature:\s*(.+?)\s*$")
SCENARIO_RE = re.compile(r"^\s*Scenario(?: Outline| Template)?:\s*(.+?)\s*$")


def summarize(path: Path) -> tuple[str, list[str]]:
    title = path.stem
    scenarios = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if m := FEATURE_RE.match(line):
            title = m.group(1)
        elif m := SCENARIO_RE.match(line):
            scenarios.append(m.group(1))
    return title, scenarios


def main() -> None:
    total = 0
    body = []
    files = sorted(FEATURES_DIR.glob("*.feature"))
    for path in files:
        title, scenarios = summarize(path)
        total += len(scenarios)
        body += ["", f"## {title}", ""]
        body += [f"- {s}" for s in scenarios] or ["- _(no scenarios)_"]
    lines = [
        "> Generated by `update-feature-summary.py` — don't edit by hand; rerun the script instead.",
        "",
        "# Feature Summary",
        "",
        "A brief list of only scenarios, grouped by feature.",
        "",
        f"- Features: `{len(files)}`",
        f"- Scenarios: `{total}`",
        *body,
    ]
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUTPUT.name}: {len(files)} features, {total} scenarios.")


if __name__ == "__main__":
    main()
